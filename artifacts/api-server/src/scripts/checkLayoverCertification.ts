/**
 * check:layover-certification — census-layover L218, spec §21's certification
 * rule, as a gate rather than a document.
 *
 *   §21  "Do not certify Layover because cards render or example itineraries
 *         look plausible. Certification must prove hard invariants across
 *         deterministic scenarios, synthetic disruption, replay, database
 *         authorization, and end-to-end lifecycle behavior."
 *
 * The certification lives in src/services/airport/layoverCertification.ts.
 * This checker enforces, on the real tree:
 *
 *   1. COMPLETE. All five §21 proof classes carry at least one entry; the seven
 *      §6.1 hard invariants (HI-1..HI-7 = L47..L53) and the fifteen §21.1
 *      scenarios (S-L219..S-L233) are each present exactly once. Prevents a row
 *      being dropped to make the certification read better.
 *   2. CITED. Every proof file exists and contains its test title verbatim.
 *      Prevents a proof that names a test someone renamed or deleted.
 *   3. EXECUTED. Every proof file is run by a real runner: an api-server node
 *      test is in package.json's `test` list; a db test matches the glob
 *      scripts/local-db/run-tests.sh runs; a client test matches the app's jest
 *      component pattern. Prevents a proof nothing executes.
 *   4. REAL DEPENDENCIES. Every migration an entry says production needs is a
 *      file in src/migrations, and every flag is seeded by some migration.
 *   5. MONOTONE. The set of unproved entries may only shrink
 *      (LAYOVER_CERTIFICATION_BASELINE.json); a baseline naming an entry that
 *      is now proved is stale and fails too, so the shrink is recorded.
 *   6. THE DOCUMENT IS THE DATA. docs/architecture/layover-certification.md
 *      carries the rendered table between its markers, byte for byte.
 *      `--write` regenerates it; the default mode only checks.
 *
 * It then REPORTS, without failing on it, which entries the proofs cover in
 * full or in part (`gaps`), and whether every production dependency the data
 * names is met on the repository's committed production records: each
 * migration in src/lib/capability/production-applied-migrations.json, each flag
 * TRUE in the current production snapshot, and no owner ruling, external
 * provider or missing data outstanding. Those records lag production, and the
 * dependencies are only the ones the data names; the report says both. Grades
 * stay census-layover's.
 *
 * Exit codes: 0 pass · 1 a rule above failed · 2 measured nothing.
 * Run: node --import tsx/esm src/scripts/checkLayoverCertification.ts [--write]
 */
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import {
  LAYOVER_CERTIFICATION,
  LAYOVER_PROOF_CLASSES,
  type CertificationEntry,
  type ProofRef,
} from "../services/airport/layoverCertification.js";
import { PRODUCTION_SNAPSHOT_URL } from "../lib/capability/snapshots/current.js";

const __dirname = dirname(fileURLToPath(import.meta.url));
const PKG_ROOT = resolve(__dirname, "../..");
const REPO_ROOT = resolve(PKG_ROOT, "../..");

export const HARD_INVARIANT_IDS = ["HI-1", "HI-2", "HI-3", "HI-4", "HI-5", "HI-6", "HI-7"] as const;
export const HARD_INVARIANT_CENSUS = ["L47", "L48", "L49", "L50", "L51", "L52", "L53"] as const;
export const SCENARIO_CENSUS = Array.from({ length: 15 }, (_, i) => `L${219 + i}`);
export const DOC_BEGIN = "<!-- layover-certification:begin (generated by check:layover-certification --write; do not edit by hand) -->";
export const DOC_END = "<!-- layover-certification:end -->";

/** Everything the rules read, so the suite can plant a world without touching the tree. */
export interface CertificationWorld {
  readRepoFile(path: string): string | null;
  /** package.json `test` script of artifacts/api-server. */
  apiTestScript: string;
  /** scripts/local-db/run-tests.sh. */
  localDbRunner: string;
  /** travel-buddy-standalone package.json `test:component` script. */
  clientComponentScript: string;
  /** File names under artifacts/api-server/src/migrations. */
  migrationFiles: readonly string[];
  /** Concatenated migration SQL, for flag seeds. */
  migrationSql: string;
  /** Baseline: ids allowed to be unproved. */
  baselineUnproved: readonly string[];
  /** Committed production records. */
  productionLedgerNames: readonly string[];
  productionFlags: Readonly<Record<string, boolean>>;
  productionRecords: string;
}

export interface EntryReport {
  id: string;
  /** "full": the proofs cover the whole claim · "part": they cover part of it (`gaps` names the rest) · "none": unproved. */
  proved: "full" | "part" | "none";
  /** Every dependency the data names is met on the committed production records. NOT a grade: census-layover may hold a row for reasons not modelled here. */
  dependenciesMet: boolean;
  /** The unmet ones, in order: owner ruling, external, data, unapplied migrations, flags off. */
  blockers: string[];
}

export interface CertificationResult {
  problems: string[];
  entries: EntryReport[];
}

const LOCAL_DB_GLOB = "src/test/db/*.db.test.ts";

function runs(proof: ProofRef, w: CertificationWorld): string | null {
  if (proof.tier === "node") {
    const rel = proof.file.replace(/^artifacts\/api-server\//, "");
    if (!proof.file.startsWith("artifacts/api-server/src/")) return "a node proof must live under artifacts/api-server/src/";
    return w.apiTestScript.split(/\s+/).includes(rel) ? null : `${rel} is not in artifacts/api-server package.json "test" — nothing runs it`;
  }
  if (proof.tier === "local_db") {
    if (!w.localDbRunner.includes(LOCAL_DB_GLOB)) return `scripts/local-db/run-tests.sh no longer runs ${LOCAL_DB_GLOB}`;
    return /^artifacts\/api-server\/src\/test\/db\/[^/]+\.db\.test\.ts$/.test(proof.file) ? null : `${proof.file} does not match ${LOCAL_DB_GLOB}`;
  }
  if (!w.clientComponentScript.includes("\\.component\\.test\\.")) return "travel-buddy-standalone test:component no longer selects *.component.test.*";
  return /^travel-buddy-standalone\/src\/.+\.component\.test\.tsx?$/.test(proof.file) ? null : `${proof.file} is not a component test the app's jest run selects`;
}

export function evaluateCertification(manifest: readonly CertificationEntry[], w: CertificationWorld): CertificationResult {
  const problems: string[] = [];
  const ids = new Set<string>();
  for (const e of manifest) {
    if (ids.has(e.id)) problems.push(`duplicate id ${e.id}`);
    ids.add(e.id);
  }
  // 1. COMPLETE
  for (const c of LAYOVER_PROOF_CLASSES) {
    if (!manifest.some((e) => e.class === c)) problems.push(`proof class ${c} has no entry — §21 names five classes`);
  }
  HARD_INVARIANT_IDS.forEach((id, i) => {
    const e = manifest.find((x) => x.id === id);
    if (!e) problems.push(`§6.1 hard invariant ${id} is missing`);
    else if (!e.census.includes(HARD_INVARIANT_CENSUS[i]!)) problems.push(`${id} must certify ${HARD_INVARIANT_CENSUS[i]}`);
  });
  for (const row of SCENARIO_CENSUS) {
    const n = manifest.filter((e) => e.id === `S-${row}`).length;
    if (n !== 1) problems.push(`§21.1 scenario S-${row} appears ${n} times, not once`);
  }
  for (const e of manifest) {
    if (!e.claim.trim()) problems.push(`${e.id} states no claim`);
    if (e.census.length === 0) problems.push(`${e.id} certifies no census row`);
    if (e.proof === null) {
      if (!e.unprovedBecause?.trim()) problems.push(`${e.id} is unproved and does not say why`);
      continue;
    }
    if (e.proof.length === 0) problems.push(`${e.id} has an empty proof list (use null and say why)`);
    for (const p of e.proof) {
      // 2. CITED
      const src = w.readRepoFile(p.file);
      if (src === null) { problems.push(`${e.id}: ${p.file} does not exist`); continue; }
      if (!src.includes(p.test)) problems.push(`${e.id}: "${p.test}" is not a title in ${p.file}`);
      // 3. EXECUTED
      const r = runs(p, w);
      if (r) problems.push(`${e.id}: ${r}`);
    }
  }
  // 4. REAL DEPENDENCIES
  for (const e of manifest) {
    for (const m of e.production.migrations ?? []) {
      const n = w.migrationFiles.filter((f) => f.startsWith(`${m}_`) && f.endsWith(".sql")).length;
      if (n !== 1) problems.push(`${e.id}: migration ${m} names ${n} files under src/migrations, not one`);
    }
    for (const f of e.production.flags ?? []) {
      if (!w.migrationSql.includes(`'${f}'`)) problems.push(`${e.id}: flag ${f} is seeded by no migration`);
    }
  }
  // 5. MONOTONE
  const unproved = manifest.filter((e) => e.proof === null).map((e) => e.id);
  for (const id of unproved) if (!w.baselineUnproved.includes(id)) problems.push(`${id} is unproved and not in the baseline — the unproved set may only shrink`);
  for (const id of w.baselineUnproved) {
    if (!ids.has(id)) problems.push(`baseline names ${id}, which the certification no longer has`);
    else if (!unproved.includes(id)) problems.push(`baseline still names ${id} as unproved, but it is proved now — remove it (the shrink is recorded by that edit)`);
  }
  // report
  const entries = manifest.map((e): EntryReport => {
    const blockers: string[] = [];
    if (e.production.ownerRuling) blockers.push(`owner ruling ${e.production.ownerRuling}`);
    if (e.production.external) blockers.push(`external: ${e.production.external}`);
    if (e.production.data) blockers.push(`data: ${e.production.data}`);
    for (const m of e.production.migrations ?? []) if (!w.productionLedgerNames.some((n) => n.startsWith(`${m}_`))) blockers.push(`migration ${m} not applied`);
    for (const f of e.production.flags ?? []) if (w.productionFlags[f] !== true) blockers.push(`flag ${f} not ON`);
    const proved = e.proof === null ? "none" : e.gaps ? "part" : "full";
    return { id: e.id, proved, dependenciesMet: blockers.length === 0, blockers };
  });
  return { problems, entries };
}

/** The certification table as the document carries it. Deterministic: same manifest, same bytes. */
export function renderCertificationTable(manifest: readonly CertificationEntry[], result: CertificationResult, records: string): string {
  const byId = new Map(result.entries.map((r) => [r.id, r]));
  const esc = (s: string) => s.replace(/\|/g, "\\|");
  const lines: string[] = [];
  for (const c of LAYOVER_PROOF_CLASSES) {
    const rows = manifest.filter((e) => e.class === c);
    const full = rows.filter((e) => byId.get(e.id)?.proved === "full").length;
    const part = rows.filter((e) => byId.get(e.id)?.proved === "part").length;
    const met = rows.filter((e) => byId.get(e.id)?.dependenciesMet).length;
    lines.push(`### ${c.replace(/_/g, " ")} — ${rows.length} entries: ${full} proved in full, ${part} in part; dependencies met on the committed production records for ${met}`, "");
    lines.push("| id | census | claim (spec words) | proved by | not covered | production still needs |", "| --- | --- | --- | --- | --- | --- |");
    for (const e of rows) {
      const proof = e.proof === null ? `**unproved** — ${esc(e.unprovedBecause ?? "")}` : e.proof.map((p) => `\`${p.file.replace(/^artifacts\/api-server\//, "")}\` "${esc(p.test)}" (${p.tier})`).join("<br>");
      const r = byId.get(e.id);
      const needs = r && r.blockers.length > 0 ? esc(r.blockers.join("; ")) : "no dependency this data names";
      lines.push(`| ${e.id} | ${e.census.join(", ")} | ${esc(e.claim)} | ${proof} | ${e.gaps ? esc(e.gaps) : "—"} | ${needs} |`);
    }
    lines.push("");
  }
  const all = result.entries;
  lines.push(`**Totals:** ${all.length} entries; ${all.filter((r) => r.proved === "full").length} proved in full and ${all.filter((r) => r.proved === "part").length} in part by registered tests; ${all.filter((r) => r.proved === "none").length} unproved. Every dependency the data names is met on the committed production records (${records}) for ${all.filter((r) => r.dependenciesMet).length}. That is not a grade: census-layover grades each row, and may hold one for a reason not modelled here.`);
  return lines.join("\n");
}

function loadWorld(): CertificationWorld {
  const read = (p: string) => (existsSync(resolve(REPO_ROOT, p)) ? readFileSync(resolve(REPO_ROOT, p), "utf8") : null);
  const pkg = JSON.parse(readFileSync(resolve(PKG_ROOT, "package.json"), "utf8"));
  const appPkg = JSON.parse(readFileSync(resolve(REPO_ROOT, "travel-buddy-standalone/package.json"), "utf8"));
  const migDir = resolve(PKG_ROOT, "src/migrations");
  const migrationFiles = readdirSync(migDir).filter((f) => f.endsWith(".sql"));
  const ledger = JSON.parse(readFileSync(resolve(PKG_ROOT, "src/lib/capability/production-applied-migrations.json"), "utf8"));
  const snapshot = JSON.parse(readFileSync(PRODUCTION_SNAPSHOT_URL, "utf8"));
  const baseline = JSON.parse(readFileSync(resolve(__dirname, "LAYOVER_CERTIFICATION_BASELINE.json"), "utf8"));
  return {
    readRepoFile: read,
    apiTestScript: String(pkg.scripts?.test ?? ""),
    localDbRunner: readFileSync(resolve(PKG_ROOT, "scripts/local-db/run-tests.sh"), "utf8"),
    clientComponentScript: String(appPkg.scripts?.["test:component"] ?? ""),
    migrationFiles,
    migrationSql: migrationFiles.map((f) => readFileSync(resolve(migDir, f), "utf8")).join("\n"),
    baselineUnproved: Array.isArray(baseline.unproved) ? baseline.unproved : [],
    productionLedgerNames: (ledger.migrations ?? []).map((m: { name?: string }) => String(m.name ?? "")),
    productionFlags: snapshot.flags ?? {},
    productionRecords: `production-applied-migrations.json (newest ${String((ledger.migrations ?? []).at(-1)?.name ?? "none")}) and the ${String(snapshot.capturedAt ?? "?")} schema snapshot's flags`,
  };
}

export const CERTIFICATION_DOC = "docs/architecture/layover-certification.md";

function main(): void {
  const world = loadWorld();
  const result = evaluateCertification(LAYOVER_CERTIFICATION, world);
  if (LAYOVER_CERTIFICATION.length === 0 || result.entries.length === 0) {
    console.error("::error::check:layover-certification measured nothing");
    process.exit(2);
  }
  const table = renderCertificationTable(LAYOVER_CERTIFICATION, result, world.productionRecords);
  // LAYOVER_CERTIFICATION_DOC: a SEAM for the suite's drift case only (a temp copy). The real-tree control sets nothing.
  const docPath = process.env.LAYOVER_CERTIFICATION_DOC ? resolve(process.env.LAYOVER_CERTIFICATION_DOC) : resolve(REPO_ROOT, CERTIFICATION_DOC);
  const doc = existsSync(docPath) ? readFileSync(docPath, "utf8") : null;
  const block = `${DOC_BEGIN}\n${table}\n${DOC_END}`;
  if (process.argv.includes("--write")) {
    if (doc === null || !doc.includes(DOC_BEGIN) || !doc.includes(DOC_END)) {
      console.error(`::error::${CERTIFICATION_DOC} is missing or has no markers; --write only fills the generated block`);
      process.exit(1);
    }
    const next = doc.slice(0, doc.indexOf(DOC_BEGIN)) + block + doc.slice(doc.indexOf(DOC_END) + DOC_END.length);
    writeFileSync(docPath, next);
    console.log(`wrote the generated block of ${CERTIFICATION_DOC}`);
  } else if (doc === null || !doc.includes(block)) {
    result.problems.push(`${CERTIFICATION_DOC} does not carry the current certification table — run: node --import tsx/esm src/scripts/checkLayoverCertification.ts --write`);
  }
  const full = result.entries.filter((r) => r.proved === "full").length;
  const part = result.entries.filter((r) => r.proved === "part").length;
  const met = result.entries.filter((r) => r.dependenciesMet).length;
  console.log(`check:layover-certification: ${result.entries.length} entries inspected across ${LAYOVER_PROOF_CLASSES.length} proof classes; ${full} proved in full, ${part} in part; dependencies met on the committed production records for ${met}`);
  for (const r of result.entries.filter((x) => x.proved !== "full" || !x.dependenciesMet)) console.log(`  ${r.id}: proved ${r.proved}${r.blockers.length ? ` — needs ${r.blockers.join("; ")}` : ""}`);
  if (result.problems.length > 0) {
    for (const p of result.problems) console.error(`::error::${p}`);
    console.error(`check:layover-certification FAILED — ${result.problems.length} problem(s)`);
    process.exit(1);
  }
  console.log("check:layover-certification PASSED");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
