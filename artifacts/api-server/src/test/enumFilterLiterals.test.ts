// ── Schema facts, read from the generated types ───────────────────────────────

/** `table.column` -> enum type name, from the `Row` annotations. */
function readColumnEnums(src: string): Map<string, string> {
  const out = new Map<string, string>();
  let cur: string | null = null;
  let inRow = false;
  for (const l of src.split("\n")) {
    let m;
    if ((m = l.match(/^      (\w+): \{$/))) { cur = m[1]!; inRow = false; continue; }
    if (cur && /^        Row: \{$/.test(l)) { inRow = true; continue; }
    if (!inRow) continue;
    if (/^        \}/.test(l)) { inRow = false; continue; }
    const c = l.match(/^          (\w+)\??: Database\["public"\]\["Enums"\]\["(\w+)"\]/);
    if (c) out.set(`${cur}.${c[1]}`, c[2]!);
  }
  return out;
}

/** enum type name -> its labels, from the exported `Constants` block. */
function readEnumLabels(src: string): Map<string, Set<string>> {
  const out = new Map<string, Set<string>>();
  const i = src.indexOf("export const Constants = {");
  assert.ok(i >= 0, "database.types.ts has no exported Constants block");
  const block = src.slice(i);
  // one-line form: `  name: ["a", "b"],`
  for (const m of block.matchAll(/^      (\w+): \[([^\][]*)\],$/gm)) {
    out.set(m[1]!, new Set([...m[2]!.matchAll(/"([^"]*)"/g)].map((x) => x[1]!)));
  }
  // multi-line form
  for (const m of block.matchAll(/^      (\w+): \[\n((?:\s+"[^"]*",\n)+)      \],$/gm)) {
    out.set(m[1]!, new Set([...m[2]!.matchAll(/"([^"]*)"/g)].map((x) => x[1]!)));
  }
  return out;
}

// ── The scan ──────────────────────────────────────────────────────────────────

/** Blank out comments, preserving byte offsets so line numbers stay right. */
function stripComments(text: string): string {
  return text
    .replace(/\/\*[\s\S]*?\*\//g, (m) => m.replace(/[^\n]/g, " "))
    .replace(/(^|[^:])\/\/[^\n]*/g, (m, p1: string) => p1 + " ".repeat(m.length - p1.length));
}

function* sourceFiles(dir: string): Generator<string> {
  for (const e of readdirSync(dir)) {
    const p = join(dir, e);
    if (statSync(p).isDirectory()) {
      if (e === "node_modules" || e === "test" || e === "__tests__") continue;
      yield* sourceFiles(p);
    } else if (/\.ts$/.test(e) && !/\.d\.ts$/.test(e) && !/\.test\.ts$/.test(e)) {
      yield p;
    }
  }
}

interface Hit { file: string; line: number; column: string; enumName: string; value: string; op: string }

function scan(colEnum: Map<string, string>, enumLabels: Map<string, Set<string>>): Hit[] {
  const hits: Hit[] = [];
  for (const abs of sourceFiles(SRC)) {
    const raw = readFileSync(abs, "utf8");
    const text = stripComments(raw);
    const file = relative(API_ROOT, abs);

    const marks: Array<{ table: string; at: number }> = [];
    for (const m of text.matchAll(/\.from\(\s*["'`](\w+)["'`]\s*\)/g)) {
      marks.push({ table: m[1]!, at: m.index! });
    }

    for (let i = 0; i < marks.length; i++) {
      const { table, at } = marks[i]!;
      const hardStop = i + 1 < marks.length ? marks[i + 1]!.at : text.length;
      const seg = text.slice(at, Math.min(hardStop, at + 2500));

      const emit = (col: string, value: string, op: string, offset: number) => {
        const key = `${table}.${col}`;
        const enumName = colEnum.get(key);
        if (!enumName) return;                       // not an enum column: harmless
        const labels = enumLabels.get(enumName);
        if (!labels) return;                         // enum we could not parse: not our call
        if (labels.has(value)) return;
        hits.push({
          file, line: text.slice(0, at + offset).split("\n").length,
          column: key, enumName, value, op,
        });
      };

      for (const x of seg.matchAll(/\.(eq|neq)\(\s*["'`](\w+)["'`]\s*,\s*["'`]([^"'`]*)["'`]\s*\)/g)) {
        emit(x[2]!, x[3]!, `.${x[1]}()`, x.index!);
      }
      for (const x of seg.matchAll(/\.in\(\s*["'`](\w+)["'`]\s*,\s*\[([^\]]*)\]/g)) {
        for (const v of x[2]!.matchAll(/["'`]([^"'`]*)["'`]/g)) emit(x[1]!, v[1]!, ".in()", x.index!);
      }
      for (const x of seg.matchAll(/\.not\(\s*["'`](\w+)["'`]\s*,\s*["'`]in["'`]\s*,\s*["'`]\(([^)]*)\)["'`]/g)) {
        for (const v of x[2]!.matchAll(/"([^"]*)"/g)) emit(x[1]!, v[1]!, '.not(…,"in",…)', x.index!);
      }
    }
  }
  return hits;
}

// ── Tests ─────────────────────────────────────────────────────────────────────

const typesSrc = readFileSync(TYPES, "utf8");
const COLUMN_ENUMS = readColumnEnums(typesSrc);
const ENUM_LABELS = readEnumLabels(typesSrc);

describe("enum filter literals — the scan's own inputs", () => {
  it("parsed a plausible number of enum-typed columns and enums", () => {
    // If a types regeneration changes the file's shape, the parse can silently
    // collapse to zero and this guard passes while checking nothing.
    assert.ok(COLUMN_ENUMS.size >= 40, `only ${COLUMN_ENUMS.size} enum-typed columns parsed — the parse broke`);
    assert.ok(ENUM_LABELS.size >= 40, `only ${ENUM_LABELS.size} enums parsed — the parse broke`);
  });

  it("resolves the columns the known defects were found on", () => {
    for (const [col, en] of [
      ["hidden_gems.status", "hidden_gem_status"],
      ["events.state", "event_state"],
      ["trips.status", "trip_status"],
      ["posts.status", "post_status"],
      ["trips.visibility", "trip_visibility"],
    ] as const) {
      assert.equal(COLUMN_ENUMS.get(col), en, `${col} no longer resolves to ${en}`);
      assert.ok((ENUM_LABELS.get(en)?.size ?? 0) > 0, `${en} has no labels`);
    }
  });

  it("does not treat text columns as enums", () => {
    // `trip_plan_items.status` is `text` (DEFAULT 'tentative'). A wrong literal
    // there is a non-match, not a 400, and flagging it would be a false alarm.
    assert.equal(COLUMN_ENUMS.get("trip_plan_items.status"), undefined);
    assert.equal(COLUMN_ENUMS.get("trip_plan_items.visibility"), undefined);
  });

  it("finds real call sites at all", () => {
    // A scan that matched nothing would pass every ratchet check below.
    const anyFrom = [...sourceFiles(SRC)].some((f) =>
      /\.from\(\s*["'`]\w+["'`]\s*\)/.test(stripComments(readFileSync(f, "utf8"))));
    assert.ok(anyFrom, "no .from(\"literal\") call sites found — the scan is inert");
  });

  it("ignores a bad literal that appears only in a comment", () => {
    const sample = `
      // .eq("status", "totally_fake")
      /* .in("status", ["also_fake"]) */
      const x = 1;`;
    assert.ok(!stripComments(sample).includes("totally_fake"));
    assert.ok(!stripComments(sample).includes("also_fake"));
    assert.equal(stripComments(sample).split("\n").length, sample.split("\n").length,
      "stripComments must preserve line count so reported line numbers stay right");
  });
});

describe("enum filter literals — no query compares an enum column to a label it lacks", () => {
  const hits = scan(COLUMN_ENUMS, ENUM_LABELS);
  const byFile = new Map<string, Hit[]>();
  for (const h of hits) {
    if (!byFile.has(h.file)) byFile.set(h.file, []);
    byFile.get(h.file)!.push(h);
  }

  it("introduces no NEW dead query", () => {
    const offenders: string[] = [];
    for (const [file, fileHits] of byFile) {
      const known = KNOWN_DEAD_QUERIES[file];
      if (!known) {
        offenders.push(
          `${file} is not in KNOWN_DEAD_QUERIES:\n` +
          fileHits.map((h) =>
            `    :${h.line}  ${h.column} ${h.op} "${h.value}" — ${h.enumName} has ` +
            `[${[...ENUM_LABELS.get(h.enumName)!].join(", ")}]`).join("\n"));
        continue;
      }
      if (fileHits.length > known.count) {
        offenders.push(
          `${file} grew from ${known.count} to ${fileHits.length} bad literal(s):\n` +
          fileHits.map((h) => `    :${h.line}  ${h.column} ${h.op} "${h.value}"`).join("\n"));
      }
    }
    assert.deepEqual(
      offenders, [],
      "A string literal compared against an enum-typed column is not one of that enum's " +
      "labels. Postgres raises 22P02 and PostgREST returns 400 — the query does not match " +
      "nothing, it FAILS, and any `if (error || !data) return []` above it will hide that.\n\n" +
      offenders.join("\n"),
    );
  });

  it("keeps the ratchet honest — a fixed file must be struck off", () => {
    const stale: string[] = [];
    for (const [file, { count }] of Object.entries(KNOWN_DEAD_QUERIES)) {
      const actual = byFile.get(file)?.length ?? 0;
      if (actual < count) {
        stale.push(
          `${file}: KNOWN_DEAD_QUERIES says ${count}, scan finds ${actual}` +
          (actual === 0 ? " — fixed; delete the entry." : ` — partly fixed; set count to ${actual}.`));
      }
    }
    assert.deepEqual(stale, [], stale.join("\n"));
  });

  it("still sees every file the 2026-09-03 sweep recorded", () => {
    // Guards against the scan quietly losing reach — a refactor that moves a
    // query behind a variable table name would otherwise read as a fix.
    const missing = Object.keys(KNOWN_DEAD_QUERIES).filter((f) => !byFile.has(f));
    assert.deepEqual(
      missing, [],
      "these files were known to contain a bad enum literal and the scan no longer sees " +
      "them at all — either they were fixed (strike them off) or the scan lost reach:\n" +
      missing.join("\n"),
    );
  });

  it("reports the total, so the backlog is visible rather than implied", () => {
    const expected = Object.values(KNOWN_DEAD_QUERIES).reduce((n, k) => n + k.count, 0);
    assert.equal(
      hits.length, expected,
      `expected ${expected} known bad literal(s), scan found ${hits.length}. ` +
      "Update KNOWN_DEAD_QUERIES in the same commit as the fix.",
    );
  });
});
