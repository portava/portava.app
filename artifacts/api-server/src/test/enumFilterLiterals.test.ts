/**
 * Enum filter-literal guard.
 *
 * THE DEFECT THIS EXISTS FOR
 * --------------------------
 * `searchHiddenGems` filtered `.in("status", ["approved", "active"])`. The enum
 * `hidden_gem_status` has labels pending | active | hidden | merged. Postgres
 * does not treat an unknown enum literal as a non-match — it raises 22P02, a
 * HARD ERROR. PostgREST turns that into a 400, supabase-js resolves
 * `{ data: null, error }` rather than throwing, and the caller's
 * `if (error || !data) return []` turns the 400 into an empty result set.
 *
 * So the search did not fail. It returned nothing, for every query, forever,
 * and looked exactly like "no gems matched".
 *
 * THE SHAPE: A STRING LITERAL COMPARED AGAINST AN ENUM-TYPED COLUMN, WHERE THE
 * STRING IS NOT ONE OF THAT ENUM'S LABELS. One bad literal kills the WHOLE
 * query — including an `.in()` list whose other values are perfectly valid —
 * because Postgres casts every element before matching any of them.
 *
 * Two properties make it near-invisible:
 *  - The same typo is HARMLESS on a `text` column (an ordinary non-match) and
 *    TOTAL on an enum column. Nothing in the call site distinguishes them.
 *  - The fixtures invent the label too. Six emitters shipped with tests that
 *    asserted on `status: "approved"`, `status: "published"`, `status:
 *    "deleted"` — values no row in either database can hold — and were green
 *    for months.
 *
 * WHAT THIS GUARD CHECKS
 * ----------------------
 * Every `.eq()` / `.neq()` / `.in()` / `.not(…, "in", …)` string literal fed to
 * a column that `src/lib/database.types.ts` declares as enum-typed, held
 * against that enum's labels. Both the column→enum mapping and the label sets
 * are read out of the generated types — no hand-transcribed schema to drift.
 *
 * KNOWN_DEAD_QUERIES below is a RATCHET, not an allowlist: it records the sites
 * that already existed when this guard was written, with what each one breaks.
 * The count per file is exact, so BOTH directions fail — a new bad literal in
 * an already-listed file, and a fixed one that was not struck off. The list is
 * meant to reach zero.
 *
 * WHAT THIS GUARD CANNOT CHECK — read this before trusting it
 * -----------------------------------------------------------
 * This is a source scan against a generated types file, not a live-schema diff.
 *
 *  - `database.types.ts` is regenerated by hand and IS observably stale for
 *    COLUMNS (it lacks `post_media.feed_url` and `profiles.phone_e164`, both
 *    live). It has not been observed to name an enum or a label that does not
 *    exist, and its labels match a 2026-09-03 production read exactly. Staleness
 *    therefore shows up as a FALSE POSITIVE on a newly added label — loud and
 *    fixable — never as a silent pass. Regenerate the types rather than
 *    allowlisting such a hit.
 *  - Table attribution is positional: a filter belongs to the nearest preceding
 *    `.from("literal")` in the same statement. `.from(tableVar)` is invisible,
 *    and so is any filter built dynamically or held in a variable.
 *  - It sees only string LITERALS. `.eq("status", someVar)` is out of scope,
 *    which is where the next instance of this class will most likely hide.
 *  - It says nothing about whether a query with only real labels asks the RIGHT
 *    question. `searchPosts` filtered `.neq("status","deleted")` using a real
 *    label while leaving `hidden` and `reported` posts publicly searchable;
 *    this guard would have passed that.
 *  - Comments are stripped before scanning, so prose describing a bad filter
 *    (including the comments explaining the fixes) is not counted.
 *
 * Sibling guards, deliberately not duplicated here: `check:write-path-columns`
 * diffs select lists against the LIVE schema ("is the query wrong?");
 * `silentSchemaErrorCatches.test.ts` finds the catches that hide the answer
 * ("would anyone find out?"). This one asks: "is the VALUE wrong?".
 */
