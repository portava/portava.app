import assert from 'node:assert/strict';
import { test } from 'node:test';
import { readFileSync } from 'node:fs';
import { PGlite } from '@electric-sql/pglite';
const migration = (name: string) => readFileSync(new URL(`../migrations/${name}`, import.meta.url), 'utf8');
const ME = '10000000-0000-4000-8000-000000000001';
const OTHER = '10000000-0000-4000-8000-000000000002';
const GEM = '20000000-0000-4000-8000-000000000001';
const COL = '30000000-0000-4000-8000-000000000001';
const COL2 = '30000000-0000-4000-8000-000000000002';

test('real SQL: legacy backfill, multiple collections, all unsave paths, exact counts, rollback, private RLS and replay', async () => {
  const db = new PGlite();
  try {
    await db.exec(`CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS;
      CREATE SCHEMA auth;
      CREATE FUNCTION auth.uid() RETURNS uuid LANGUAGE sql STABLE AS $$ SELECT nullif(current_setting('test.uid',true),'')::uuid $$;
      CREATE TYPE public.collection_entity_type AS ENUM('post');
      CREATE TABLE public.collections(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),owner_id uuid NOT NULL,name text NOT NULL,is_default boolean NOT NULL DEFAULT false,position integer NOT NULL DEFAULT 0);
      CREATE UNIQUE INDEX ON public.collections(owner_id) WHERE is_default;
      CREATE TABLE public.collection_items(id uuid PRIMARY KEY DEFAULT gen_random_uuid(),collection_id uuid NOT NULL REFERENCES public.collections(id) ON DELETE CASCADE,entity_type public.collection_entity_type NOT NULL,entity_id uuid NOT NULL,saved_at timestamptz NOT NULL DEFAULT now(),UNIQUE(collection_id,entity_type,entity_id));
      CREATE TABLE public.hidden_gems(id uuid PRIMARY KEY,save_count integer NOT NULL DEFAULT 0);
      CREATE TABLE public.hidden_gem_saves(user_id uuid NOT NULL,gem_id uuid NOT NULL REFERENCES public.hidden_gems(id) ON DELETE CASCADE,saved_at timestamptz NOT NULL DEFAULT now(),PRIMARY KEY(user_id,gem_id));
      ALTER TABLE public.collections ENABLE ROW LEVEL SECURITY;
      ALTER TABLE public.collection_items ENABLE ROW LEVEL SECURITY;
      ALTER TABLE public.hidden_gem_saves ENABLE ROW LEVEL SECURITY;
      CREATE POLICY own ON public.collections USING(owner_id=auth.uid()) WITH CHECK(owner_id=auth.uid());
      CREATE POLICY own ON public.collection_items USING(EXISTS(SELECT 1 FROM public.collections c WHERE c.id=collection_id AND c.owner_id=auth.uid())) WITH CHECK(EXISTS(SELECT 1 FROM public.collections c WHERE c.id=collection_id AND c.owner_id=auth.uid()));
      CREATE POLICY own ON public.hidden_gem_saves USING(user_id=auth.uid()) WITH CHECK(user_id=auth.uid());
      GRANT USAGE ON SCHEMA public,auth TO authenticated,service_role;
      GRANT ALL ON ALL TABLES IN SCHEMA public TO authenticated,service_role;
      INSERT INTO public.hidden_gems(id,save_count) VALUES('${GEM}',999);
      INSERT INTO public.hidden_gem_saves(user_id,gem_id,saved_at) VALUES('${ME}','${GEM}','2026-01-01');
      INSERT INTO public.collections(id,owner_id,name) VALUES('${COL}','${ME}','Food'),('${COL2}','${ME}','Travel');`);
    await db.exec(migration('4011_gem_collection_type.sql'));
    await db.exec(migration('4012_gem_collection_bridge.sql'));
    const count = async (table: string) => Number((await db.query<{ n: number }>(`SELECT count(*) n FROM ${table}`)).rows[0]!.n);
    const savedCount = async () => (await db.query<{ save_count: number }>('SELECT save_count FROM hidden_gems')).rows[0]!.save_count;
    assert.equal(await count('collection_items'),1); assert.equal(await savedCount(),1);
    assert.equal(new Date((await db.query<{ saved_at: Date }>('SELECT saved_at FROM collection_items')).rows[0]!.saved_at).toISOString(), '2026-01-01T00:00:00.000Z');
    await db.exec(migration('4012_gem_collection_bridge.sql'));
    assert.equal(await count('collection_items'),1,'backfill is idempotent');
    await db.exec(`SET ROLE authenticated; SET test.uid='${ME}'; INSERT INTO collection_items(collection_id,entity_type,entity_id) VALUES('${COL}','gem','${GEM}'),('${COL2}','gem','${GEM}');`);
    assert.equal(await count('collection_items'),3); assert.equal(await savedCount(),1,'one bookmark despite multiple folders');
    await db.exec(`DELETE FROM collection_items WHERE collection_id='${COL}'`);
    assert.equal(await count('hidden_gem_saves'),1,'removing one filing keeps bookmark');
    await db.exec(`DELETE FROM hidden_gem_saves WHERE gem_id='${GEM}'`);
    assert.equal(await count('collection_items'),0); assert.equal(await savedCount(),0,'legacy unsave removes all filings');
    await db.exec(`INSERT INTO collection_items(collection_id,entity_type,entity_id) VALUES('${COL}','gem','${GEM}')`);
    assert.equal(await count('hidden_gem_saves'),1); assert.equal(await savedCount(),1);
    await db.exec('DELETE FROM collection_items');
    assert.equal(await count('hidden_gem_saves'),0); assert.equal(await savedCount(),0,'last filing removes legacy bookmark');
    await db.exec(`INSERT INTO hidden_gem_saves(user_id,gem_id) VALUES('${ME}','${GEM}')`);
    assert.equal(await count('collection_items'),1,'old clients file automatically');
    await db.exec(`SET test.uid='${OTHER}'`);
    assert.equal(await count('collection_items'),0,'another account cannot enumerate private saves');
    await assert.rejects(db.exec(`INSERT INTO collection_items(collection_id,entity_type,entity_id) VALUES('${COL}','gem','${GEM}')`),/row-level security/);
    await db.exec(`SET test.uid='${ME}'`);
    await assert.rejects(db.exec(`UPDATE hidden_gem_saves SET user_id='${OTHER}'`),/remove_and_add|row-level security/);
    await db.exec(`RESET ROLE; SET test.uid=''; ALTER TABLE hidden_gems ADD CONSTRAINT fail_counter CHECK(save_count<2);`);
    await assert.rejects(db.exec(`INSERT INTO hidden_gem_saves(user_id,gem_id) VALUES('${OTHER}','${GEM}')`),/fail_counter/);
    assert.equal(await count('hidden_gem_saves'),1); assert.equal(await savedCount(),1,'failed aggregate rolls back entire save');
    assert.equal(Number((await db.query<{n:number}>(`SELECT count(*) n FROM collections WHERE owner_id='${OTHER}'`)).rows[0]!.n),0,'default folder also rolled back');
    const callable = await db.query<{ allowed:boolean }>(`SELECT has_function_privilege('authenticated','collection_internal.bridge_gem_bookmark()','EXECUTE') allowed`);
    assert.equal(callable.rows[0]!.allowed,false,'privileged bridge is not a callable client RPC');
  } finally { await db.close(); }
});
