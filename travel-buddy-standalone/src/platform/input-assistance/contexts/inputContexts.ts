/** Look up a context descriptor. Returns the `generic_text` descriptor if the
 *  context is somehow unknown (defensive — the union should prevent this). */
export function getContextDescriptor(context: InputContext): InputContextDescriptor {
  return INPUT_CONTEXT_REGISTRY[context] ?? INPUT_CONTEXT_REGISTRY.generic_text;
}
