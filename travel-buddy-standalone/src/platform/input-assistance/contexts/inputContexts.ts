/**
 * Global Input Intelligence — the InputContext registry (spec §5).
 *
 * The single source of truth for "what assistance is allowed" per context.
 * Each context carries the default behavioral shape (mode, entity types,
 * privacy, offline, capability flags, zero-state affordance). `inputPolicies.ts`
 * builds concrete per-field `InputFieldPolicy` objects from these descriptors;
 * a field may override any default when it registers.
 *
 * These defaults are derived directly from the spec's field/mode tables
 * (§ "Field | Mode | Primary assistance", §12–§14, §26, §54–§56) and the audit's
 * desired-mode column. Nothing here is wired to a screen yet (additive spine).
 */
import type {
  AssistanceType,
  EntityType,
  InputContext,
  OfflineInputPolicy,
  PrivacyClass,
} from '../types/inputContext.ts';
import type { InputAssistanceMode } from '../types/fieldPolicy.ts';

/** Canonical policy schema version returned on every projection (§41, §48). */
export const INPUT_POLICY_VERSION = 'input-2026-08';

export interface InputContextDescriptor {
  context: InputContext;
  /** Default assistance mode for fields of this context. */
  defaultMode: InputAssistanceMode;
  /** Entity classes this context resolves into (empty for pure text fields). */
  entityTypes: EntityType[];
  /** Assistance types this context may surface by default. */
  allowedSuggestionTypes: AssistanceType[];
  privacyClass: PrivacyClass;
  offlinePolicy: OfflineInputPolicy;
  allowPersonalization: boolean;
  allowLiveContext: boolean;
  allowMemoryContext: boolean;
  allowAI: boolean;
  /** §14 — does this field offer useful zero-character suggestions? */
  zeroStateAssistance: boolean;
  /** Default minimum characters before server-assisted suggestions (§33). */
  minChars: number;
}

