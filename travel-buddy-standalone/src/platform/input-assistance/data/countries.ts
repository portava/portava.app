/**
 * §32 G197 / §34 G212 — the SHIPPED country dictionary.
 *
 * ── WHY THIS FILE EXISTS ─────────────────────────────────────────────────────
 *
 * `country_picker`'s offline policy is `static_dictionary` — the authority says
 * this field MAY answer from a local list when the server is unreachable. Until
 * this file there was no such list: `contexts/fieldInventory.ts` recorded the
 * consequence in as many words — "the client ships no country list, so an
 * offline country picker would return nothing". The gate was real and the
 * substrate was missing. This is the substrate.
 *
 * ── HOW THIS SET WAS BOUNDED, EXACTLY ────────────────────────────────────────
 *
 * Every code currently assigned in ISO 3166-1 alpha-2, named by the CLDR
 * English region names that ship with Node's ICU at generation time. 250
 * entries. The generator is recorded here rather than kept: the artifact is the
 * committed literal below, not a build step, because a dictionary that is
 * regenerated at install time is a dictionary whose contents nobody reviewed.
 *
 * WHAT IT OMITS, stated so a reader does not have to infer it:
 *   - subdivisions (ISO 3166-2) — no states, provinces or regions;
 *   - historical and withdrawn codes (DD, SU, YU, ZR, …) and the deprecated
 *     aliases ICU still answers for;
 *   - the supranational and exceptionally-reserved codes ICU mixes into the
 *     same range (EU, UN, EZ, UK-as-alias, the XA/XB pseudo-locales, ZZ);
 *   - every kind of identity: no ISO-3 code, no flag, no coordinates, no
 *     Portava entity id. See `types.ts` for why the last one is deliberate.
 *
 * DISPLAY SPELLING IS THE APP'S, NOT CLDR's. Where the two disagree the app
 * wins, because the rest of Portava already stores and renders these strings —
 * `user_stamps.country` holds "Czech Republic" and "Turkey", and an offline
 * picker that inserted "Czechia" or "Türkiye" would fork the display spelling
 * §10 says is never rewritten. The divergences were enumerated, not guessed:
 * Czechia, Türkiye, the two Congos, the two SAR spellings, Myanmar (Burma),
 * Palestinian Territories, the `&`/`and` and `St.`/`Saint` conventions. The
 * CLDR spelling of each survives as an ALIAS, so someone who types "Czechia"
 * still finds the row.
 *
 * ── THE PIN THAT KEEPS IT HONEST ─────────────────────────────────────────────
 *
 * `__tests__/localDictionaries.test.ts` asserts that EVERY country name the app
 * already ships in `src/lib/countryCentroids.ts` — the passport-map artifact,
 * 149 keys including its own colloquial aliases — is reachable in this
 * dictionary, as a label or as an alias. That is what stops this file becoming
 * a second, drifting country list: the artifact that was already here is the
 * floor, and a name that can be pinned on the passport map can always be picked
 * in a country field, offline included.
 */
